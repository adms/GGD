#!/usr/bin/env bash
#
# 🚢 GGD 自動分級出貨 —— `pnpm ship`
#
# ═══════════════════════════════════════════════════════════════════════════
# 為什麼這支存在
# ═══════════════════════════════════════════════════════════════════════════
#
# owner 2026-08-23：
#   「或是其他**輕量級動態線上上架方式 (hotfix, patch) 設計與建議**，
#     並且要**能自動化判斷執行**」
#   「最後記得**全部規則轉成自動化指令避免疏漏忘記**」
#
# 在此之前，「這一次要不要重建映像」是**我看著 diff 用猜的**，而 CLAUDE.md 記著
# 判準 0/4 全破。這支把它換成一支會自己回非零的程式：
#
#   路徑集合 → tiers.json 分級 → 只跑該跑的閘 → 版號 → push → note → 部署 → 煙霧
#
# ⛔ 三條硬規則（⛔ 動這支之前先讀）：
#   ① **分級只決定「跑不跑」，⛔ 不改任何一支閘的判準。**
#      08-01／08-02 兩次「全綠而線上整個掛掉」的教訓是**閘不夠**，⛔ 不是閘太多。
#   ② **fail-closed**：路徑對不到規則、認不得線上版本、閘紅了 —— 一律往「多跑／停」倒。
#   ③ **會改到別人看得到的東西那幾步（tag / push / gh / 部署）預設只印不跑**，
#      要 `--execute` 才真的跑。⛔ 併行 lane 一律不自己 push/deploy。
#
# ═══════════════════════════════════════════════════════════════════════════
# 用法
# ═══════════════════════════════════════════════════════════════════════════
#
#   pnpm ship --stamp "v0.25.7-3-gabc1234"   # ⭐ 起點＝線上右下角的版本徽章
#   pnpm ship --deployed <sha> [--head <ref>]
#   pnpm ship --plan-only                    # 只印計畫，⛔ 一個閘都不跑
#   pnpm ship --execute --tag "說明" --notes docs/_release/<檔>.md
#
# ⚠️ **起點是「線上正在服務的那個 commit」，⛔ 不是「我這次改了什麼」。**
#    2026-08-02 的事故就是那一次 push 裡 content 與 schema 都動了，
#    而只有 content 被送上去 —— 用累計 diff 判，那一次會落在 T3。
#
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
exec node tools/deploy-timing/pipeline.mjs "$@"
