/** 一頁的標籤（不認得的 pageId 回空陣列 —— ⛔ 不要為了找不到就丟例外）。 */
export function tagsOf(page: string): readonly NavTag[] {
  return NAV_TAGS[page] ?? [];
}

/** 帶著這個標籤的所有頁（順序＝`NAV_TAGS` 的宣告順序，也就是左欄的順序）。 */
export function pagesWithTag(tag: NavTag): string[] {
  return Object.keys(NAV_TAGS).filter((p) => NAV_TAGS[p]!.includes(tag));
}

/** 每個標籤各有幾頁 —— UI 要在按鈕上印數量時用它，⛔ 不要在元件裡再數一次。 */
export function tagCounts(): Record<NavTag, number> {
  const out = {} as Record<NavTag, number>;
  for (const tag of TAG_VOCAB) out[tag] = 0;
  for (const tags of Object.values(NAV_TAGS)) for (const tag of tags) out[tag] += 1;
  return out;
}
