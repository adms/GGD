/**
 * padFocusLanding — GH#514：一塊捲動區要能被手把**捲動**，先要能被手把**站上去**。
 *
 * ---------------------------------------------------------------------------
 * 為什麼「捲動機制做好了」還不夠
 * ---------------------------------------------------------------------------
 * #505/K3 把捲動那一半做完了，而它的 `scrollTargetFor` 是從**目前的焦點**往上找
 * 最近的可捲祖先（`PadFocusNav.tsx`）。所以一塊**沒有任何可聚焦子元素**的捲動區，
 * 對手把來說是不存在的 —— 焦點永遠放不進去，右搖桿與方向鍵都到不了：
 *
 *   · 宿敵榜的每一列都是純 `<div>`（沒有按鈕、沒有 tabindex）
 *   · 好友清單的列只有「我是房主且對方在線」時才長出 Invite 按鈕
 *   · 英靈殿的故事描述是一個 56px 高的純文字框
 *   · 排行榜的名次列同樣是純 `<div>`，「載入更多」只有還有下一頁時才在
 *
 * 這四塊在滑鼠上完全正常（滾輪不需要焦點），所以**沒有任何既有守衛會紅**。
 *
 * ---------------------------------------------------------------------------
 * ⛔ 這不是替每個面板寫一次
 * ---------------------------------------------------------------------------
 * `[data-pad-focusable]` 早就列在 `PadFocusNav.FOCUSABLE_SELECTOR` 裡 —— 它是
 * **既有的 opt-in 機制**，引擎一個字都不必改。這個檔只是把「那一組屬性」收成
 * 一個住處，五個面板各展開一次（CLAUDE.md 第零守則⑨：N 個同型 = K 個模板 + 一張表），
 * 而那張表就是 `platform/lobbyPadFocusLanding.test.ts`。
 *
 * ⚠️ `tabIndex: -1` 是**必要的另一半**，⛔ 不是可有可無的裝飾：
 * `[data-pad-focusable]` 只讓 pad **看得見**這個框，但一個沒有 tabindex 的
 * `<div>` 呼叫 `.focus()` 是**完全沒有反應**的 —— 焦點環會亮在一個
 * `document.activeElement` 從來沒有移動過的地方，而畫面上看起來一模一樣
 * （CLAUDE.md 失敗形態②：算出來了但從沒送到消費端）。
 * ⛔ 也不可以寫 `0`：那會把每一塊捲動區塞進鍵盤的 Tab 序列，
 * 讓鍵盤玩家在真正的控制項之間多按四下。
 *
 * 落點掛在**容器**上而不是逐列，因為那是唯一在**空清單／載入中／讀取失敗**
 * 三種狀態下都還在的元素 —— 而「清單是空的」正是手把最需要能捲進去看說明的時候。
 */
export interface PadFocusLandingProps {
  "data-pad-focusable": string;
  tabIndex: -1;
}

/** 把一個純顯示的捲動框變成手把的焦點落點（＋因此變成捲動錨點）。 */
export function padFocusLanding(): PadFocusLandingProps {
  return { "data-pad-focusable": "", tabIndex: -1 };
}
