def crosswalk(records):
    by_id = {}
    for work, kind, ids in GROUPS:
        for hero_id in ids:
            if hero_id in by_id:
                raise ValueError(f'Duplicate curated origin: {hero_id}')
            by_id[hero_id] = (work, kind)
    actual = {r['id'] for r in records}
    if actual != set(by_id):
        raise ValueError(f'Origin coverage mismatch: missing={actual-set(by_id)}, extra={set(by_id)-actual}')
    result = {}
    for record in records:
        hero_id = record['id']
        work, kind = by_id[hero_id]
        sources = [f'https://300data.com/hero/{hero_id}.html',
                   f'https://300data.com/data/api/hero_info/id/{hero_id}']
        sources += MORE_SOURCES.get(hero_id, [])
        status = '角色身分對照'
        if hero_id in (18,23,56,61):
            status = '題材確認；具體改編版本未定'
        elif hero_id == 187:
            status = '系列確認；具體人物未定'
        elif hero_id in (390,392):
            status = '依模型路徑推定技能歸屬'
        elif hero_id in (54,119,126):
            status = '已對照；含跨作或改名沿革'
        result[hero_id] = {
            'canonical_character': ALIASES.get(hero_id, record['name_original']),
            'origin_work': work,
            'origin_type': kind,
            'origin_status': status,
            'origin_note': NOTES.get(hero_id,''),
            'related_origin_work': '庫洛魔法使／魔卡少女櫻' if hero_id == 119 else '',
            'origin_sources': list(dict.fromkeys(sources)),
            'origin_local_evidence': f'evidence/hero-backgrounds/{hero_id}.json',
        }
    return result
