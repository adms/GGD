  const [pairs, indexed, qualityPath, archive, out] = process.argv.slice(2).map(x => path.resolve(x));
  assert(pairs && indexed && qualityPath && archive && out && process.argv.length === 7, 'USAGE: PAIRS INDEXED QUALITY_JSON CATALOG_ARCHIVE NEW_DIR');
  assert(!fs.existsSync(out), 'OUTPUT_ALREADY_EXISTS');
  const pins = {};
  const read = file => { const bytes = fs.readFileSync(file); pins[file] = sha(bytes); return JSON.parse(bytes); };
  const manifest = read(path.join(pairs, 'manifest.json'));
  const examples = read(path.join(pairs, 'examples.json'));
  assert.equal(pins[path.join(pairs, 'examples.json')], manifest.outputs['examples.json']);
  const quality = read(qualityPath);
  assert.equal(quality.pairManifestSha256, pins[path.join(pairs, 'manifest.json')]);
  const indexes = read(path.join(indexed, 'catalog-indexes.json'));
  assert.equal(indexes.sourceCatalogsSha256, manifest.outputs['catalogs.json']);
  const modelMetadata = read(path.join(indexed, 'projection-verified/models.json'));
  const catalogManifest = read(path.join(archive, 'catalog-version.json'));
  const fileMap = new Map(catalogManifest.files.map(f => [f.path, f]));
  const publicIds = {};
  for (const collection of ['models', 'vfx', 'projectiles', 'status-effects', 'champions']) {
    const name = `catalog/${collection}/_index.json`, entry = fileMap.get(name);
    assert(entry, 'CATALOG_INDEX_MISSING:' + collection);
    const file = path.join(archive, name), index = read(file);
    assert.equal('sha256:' + pins[file], entry.sha256, 'CATALOG_INDEX_DRIFT');
    publicIds[collection] = index.entries.map(e => e.id);
  }
  // The same complete catalog index is supplied to every hero. No reference
  // shortlist is selected by the example's answer, source tags, or expected IDs.
  const assets = {schema: 'ggd-generation-asset-index@1', prefixTableRule: 'Each key is a literal prefix. Concatenate with exactly one listed suffix; not wildcard permission.',
    byCollection: Object.fromEntries(Object.entries(publicIds).map(([key, ids]) => [key, prefixTable(ids)])),
    uploadedModels: Object.entries(modelMetadata).map(([id, m]) => ({id, source: m.source})),
    icons: prefixTable(catalogManifest.files.filter(f => f.path.startsWith('assets/icons/')).map(f => f.path)),
    warning: 'Asset source identity is not a guarantee of exact identity match to this hero. Model selection does not certify asset closure or runtime readiness.'};
  const {rows, devGroups, grouping} = splitExamples(examples, quality);
  const data = rows.map(e => {
    const target = learningTarget(e.target);
    const user = {request: e.request, outputContract: {format: target.format, heroId: e.heroId,
      heroName: e.request.heroName, slot: e.slot, abilityIdPattern: `${e.heroId}.<lowercase-slot>`, planId: `${e.heroId}.plan`, contract: CONTRACT},
      allowedCatalog: indexes.indexes[e.provenance.gameRevision], assets};
    return {id: e.id, heroId: e.heroId, groupId: e.groupId, originalGroupId: e.originalGroupId, slot: e.slot, split: e.split,
      teacherSha256: e.teacherSha256, inputKind: e.inputKind, engineRevision: e.provenance.gameRevision,
      historicalExposure: 'Existing teacher sources were used or inspected in previous experiments; new train examples make their old tests seen regressions. Internal dev is not the future blind batch.',
      messages: [{role: 'system', content: SYSTEM}, {role: 'user', content: JSON.stringify(user)}, {role: 'assistant', content: JSON.stringify(target)}],
      inputSha256: hash(user), targetSha256: hash(target)};
  });
  const counts = Object.fromEntries(['train', 'dev'].map(split => [split, {
    tasks: data.filter(e => e.split === split).length,
    wholeHeroes: data.filter(e => e.split === split && e.slot === 'HERO').length,
    slots: data.filter(e => e.split === split && e.slot !== 'HERO').length,
    groups: new Set(data.filter(e => e.split === split).map(e => e.groupId)).size,
  }]));
  const trainGroups = new Set(data.filter(e => e.split === 'train').map(e => e.groupId));
  assert(devGroups.every(g => !trainGroups.has(g)), 'HERO_GROUP_LEAKAGE');
  fs.mkdirSync(out, {recursive: true});
  const outputs = {};
  function write(name, value, jsonl = false) {
    const text = jsonl ? value.map(v => JSON.stringify(v)).join('\n') + '\n' : JSON.stringify(value, null, 2) + '\n';
    fs.writeFileSync(path.join(out, name), text, {flag: 'wx'}); outputs[name] = sha(text);
  }
  write('examples.json', data); write('contract.json', CONTRACT); write('assets.json', assets); write('grouping.json', grouping);
  for (const split of ['train', 'dev']) write(split + '.jsonl', data.filter(e => e.split === split), true);
  write('manifest.json', {schema: 'ggd-distillation-frozen-data@1', counts, devGroups,
    inputs: pins, outputs, scriptSha256: sha(fs.readFileSync(fileURLToPath(import.meta.url))),
    trainingSelection: 'one traversal of all train tasks, no replacement or automatic sweep',
    inferencePolicy: 'fixed single-pass index+contract context for initial A/B. Full validators have complete engine contracts. No teacher-answer lookup or Codex repair.',
    qualityPolicy: quality.policy, sourceQualityCounts: quality.counts,
    newBlindBatch: 'not supplied; never inserted into this split',
    metricsPolicy: 'primary source/mechanism/whole-hero outcomes; CE/exact match are diagnostics only',
    checkpointPolicy: 'fixed end of one epoch, intermediate recovery checkpoints not selected on dev',
    frozenWeightsStarted: false, releaseQualified: false});
