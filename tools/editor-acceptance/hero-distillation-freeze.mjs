export function learningTarget(target) {
  const t = structuredClone(target);
  const slots = t.format === 'hero-plan' ? Object.values(t.plan.slots) : t.format === 'hero-slot' ? [t.slot] : [];
  for (const slot of slots) for (const product of slot.products) delete product.template.contentSha256;
  return t;
}

/** Prefix sharing is exact, not a regex allowing nonexistent asset IDs. */
export function prefixTable(ids) {
  const groups = {};
  for (const id of [...new Set(ids)].sort()) {
    const slash = id.lastIndexOf('/');
    // A path's extension is not useful prefix sharing. For hero.q.webp keep
    // hero. shared; for hero.webp share its containing directory.
    const i = slash >= 0 ? Math.max(slash, id.lastIndexOf('.', id.lastIndexOf('.') - 1)) : id.lastIndexOf('.');
    const prefix = id.slice(0, i + 1), suffix = id.slice(i + 1);
    (groups[prefix] ??= []).push(suffix);
  }
  return groups;
}

const normalizedText = value => String(value ?? '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
const grams = text => new Set(Array.from({length: Math.max(0, text.length - 3)}, (_, i) => text.slice(i, i + 4)));
export function nearDuplicateGroups(examples, selected) {
  const heroIds = [...new Set(selected.map(e => e.heroId))].sort();
  const parent = new Map(heroIds.map(id => [id, id]));
  const find = id => parent.get(id) === id ? id : find(parent.get(id));
  const edges = [], byGroup = new Map();
  const connect = (a, b, reason, similarity) => {
    const roots = [find(a), find(b)].sort(); parent.set(roots[1], roots[0]);
    edges.push({a, b, reason, ...(similarity === undefined ? {} : {similarity})});
  };
  const signatures = heroIds.map(id => {
    const e = examples.find(e => e.heroId === id && e.slot === 'HERO');
    assert(e, 'WHOLE_HERO_SOURCE_REQUIRED_FOR_GROUPING');
    if (byGroup.has(e.groupId)) connect(id, byGroup.get(e.groupId), 'same-declared-hero-family');
    else byGroup.set(e.groupId, id);
    const source = normalizedText(Object.values(e.request.slots ?? {}).map(s => s.description ?? '').join('\n'));
    return {id, name: normalizedText(e.request.heroName), source, grams: grams(source)};
  });
  let largestUngroupedSimilarity = 0;
  for (let i = 0; i < signatures.length; i++) for (let j = i + 1; j < signatures.length; j++) {
    const a = signatures[i], b = signatures[j];
    if (a.name && a.name === b.name) { connect(a.id, b.id, 'same-normalized-hero-name'); continue; }
    if (a.source && a.source === b.source) { connect(a.id, b.id, 'same-six-slot-source'); continue; }
    if (Math.min(a.source.length, b.source.length) < 150) continue;
    const intersection = [...a.grams].filter(g => b.grams.has(g)).length;
    const similarity = intersection / (a.grams.size + b.grams.size - intersection);
    if (similarity >= 0.85) connect(a.id, b.id, 'six-slot-source-4gram-jaccard-at-least-0.85', similarity);
    else largestUngroupedSimilarity = Math.max(largestUngroupedSimilarity, similarity);
  }
  // The original group key remains stable when no new duplicate family is
  // found. Transitive matches keep all complete/slot tasks on the same side.
  const components = new Map();
  for (const id of heroIds) (components.get(find(id)) ?? (components.set(find(id), []), components.get(find(id)))).push(id);
  const groupByHero = {};
  for (const ids of components.values()) {
    const group = selected.filter(e => ids.includes(e.heroId)).map(e => e.groupId).sort()[0];
    for (const id of ids) groupByHero[id] = group;
  }
  return {groupByHero, edges, largestUngroupedSimilarity,
    policy: 'Declared hero/transform families, normalized identical names, identical six-slot sources, and source character 4-gram Jaccard >= 0.85 (minimum 150 characters). This is a deterministic near-duplicate screen, not proof of all semantic independence.'};
}

export function splitExamples(examples, quality) {
  const eligible = new Set(quality.tasks.filter(t => t.trainingEligible).map(t => t.id));
  const candidates = examples.filter(e => eligible.has(e.id));
  const grouping = nearDuplicateGroups(examples, candidates);
  const selected = candidates.map(e => ({...e, originalGroupId: e.groupId, groupId: grouping.groupByHero[e.heroId]}));
  const whole = selected.filter(e => e.slot === 'HERO');
  const formatCounts = new Map();
  for (const e of whole) formatCounts.set(e.target.format, (formatCounts.get(e.target.format) ?? 0) + 1);
  // Two development heroes, selected before inference. Keep at least one
  // complete training hero for each authoring format (only one community full
  // hero survives the source-quality screen). Do not use the future new batch.
  const ranked = [...whole].sort((a, b) => sha('distill-split-v1:' + a.groupId).localeCompare(sha('distill-split-v1:' + b.groupId)));
  const dev = new Set();
  for (const e of ranked) {
    if (dev.size === 2) break;
    if (dev.has(e.groupId)) continue;
    const groupFormats = new Map();
    for (const member of whole.filter(r => r.groupId === e.groupId)) groupFormats.set(member.target.format, (groupFormats.get(member.target.format) ?? 0) + 1);
    if ([...groupFormats].some(([format, n]) => formatCounts.get(format) - n < 1)) continue;
    dev.add(e.groupId);
    for (const [format, n] of groupFormats) formatCounts.set(format, formatCounts.get(format) - n);
  }
  assert.equal(dev.size, 2, 'INSUFFICIENT_INTERNAL_DEV_GROUPS');
  const rows = selected.map(e => ({...e, split: dev.has(e.groupId) ? 'dev' : 'train'}));
  // Identical source or complete target evidence cannot straddle the split.
  // Shared generic templates alone are not identical hero demonstrations.
  for (const key of ['request', 'target']) {
    const seen = new Map();
    for (const e of rows.filter(e => e.slot === 'HERO')) {
      const signature = hash(e[key]);
      if (seen.has(signature)) assert.equal(seen.get(signature), e.split, 'EXACT_HERO_LEAKAGE');
      seen.set(signature, e.split);
    }
  }
  return {rows, devGroups: [...dev].sort(), grouping};
}

