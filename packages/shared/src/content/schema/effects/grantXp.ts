/**
 * ⭐⭐ GH#890 —— **每秒額外獲得經驗值**。
 *
 * owner 2026-09-01（逐字）：
 * > 「把這兩招都改成**額外獲得**而非奪取就好，**原木則改為經驗值**，
 * >  這樣就可以很快實作驗收關票⋯**不要一直卡住不值得花更多成本**」
 *
 * ── ⛔ 在此之前 ────────────────────────────────────────────────────────
 * 92-002 最終戈壁的卡面寫著「每秒可以額外**奪得 75 原木**」——
 * ⭐ 而這個遊戲**沒有原木**（46 個 effect kind 裡零個）⇒ 卡面在說一件
 * 結構上不可能發生的事（第一·五守則）。
 *
 * ⇒ ⭐ owner 的裁決把它換成一個**做得到的等效機制**：經驗值。
 * ⚠️ 而 sim 端的 `economy/progression.ts::grantXp()` **早就存在** ——
 * ⛔ 缺的只是一個把它接出來的 effect kind（第〇·五守則：機制在引擎、技能是資料）。
 *
 * ── ⭐ 為什麼**不**做成 `grantGold` 的一個 `resource` 欄位 ────────────────
 * 兩者的**語意分岔**：金錢有「發放倍率／分類」（`GoldPayoutCategory` —— 打英雄
 * 與打殭屍是不同的桶），⭐ 而經驗**沒有那個概念**。把它們併成一格，那幾個
 * 金錢專屬的欄位在經驗那一邊就是「說了但不會發生」（第一·五守則）。
 */
import { z } from "zod";
import { EFFECT_COMMON_SHAPE } from "./_shared";

export const zGrantXp = z
  .object({
    kind: z.literal("grantXp"),
    ...EFFECT_COMMON_SHAPE,
    /**
     * 固定經驗值。
     * ⚠️ 上界 **50,000** 是**誤打守衛**（⛔ 不是平衡政策）：一次 500,000 會直接
     * 把一個角色從 1 級推到滿級，⭐ 而那是打錯字的樣子，⛔ 不是設計的樣子。
     */
    flat: z.number().min(0).max(50_000),
    /**
     * 誰收：施法者（預設）或每一個解析出來的目標。
     * ⚠️ ⭐ 沒有 `"steal"` —— owner 逐字要的是「**額外獲得**而非奪取」。
     * ⛔ 而奪取需要一個「從誰身上扣」的機制，那是另一件事。
     */
    to: z.enum(["self", "target"]).optional(),
  })
  .strict();
