/** 依索引取旋轉子；`signed` 為負時把 sin 取反（＝負角）。⛔ 越界夾住，不擲。 */
function rotAt(halfDegrees: number): readonly [number, number] {
  const i = halfDegrees < 0 ? -halfDegrees : halfDegrees;
  const capped = i > FAN_UNIT_ROTATION.length - 1 ? FAN_UNIT_ROTATION.length - 1 : i;
  const r = FAN_UNIT_ROTATION[capped] ?? FAN_UNIT_ROTATION[0]!;
  return halfDegrees < 0 ? [r[0], -r[1]] : r;
}

/** 複數乘法 `(x + i·z) × (c + i·s)`。⭐ 只有 + − ×。 */
function rotate(
  v: { x: number; z: number },
  r: readonly [number, number],
): { x: number; z: number } {
  return { x: v.x * r[0] - v.z * r[1], z: v.x * r[1] + v.z * r[0] };
}

/**
 * ⭐ 以 `facing` 為中心、相鄰兩臂相隔 `spreadDeg` 的 `count` 個**單位方向**。
 *
 * ⚠️ ⭐ `spreadDeg` 是**相鄰兩臂之間**的角度，⛔ 不是總張角 ——
 * 原作 A09I 是「中央一條 ＋ 兩側各 45°」⇒ `count:3, spreadDeg:45`
 * 逐字翻成 `facing−45 · facing · facing+45`。
 *
 * ⚠️ 總張角 `(count−1) × spreadDeg` 夾在 {@link FAN_MAX_TOTAL_DEG}：
 * ⛔ 超過就**壓縮間距**（⛔ 不是丟掉幾臂 —— 少一條龍是玩家看得見的，
 * 而扇窄一點不是）。
 *
 * @param facing ⛔ 不需要先正規化（內部處理）。長度 0 ⇒ 回空陣列
 *               （⭐ 與 `modelFxPlacement` 對「面向解不到」的既有處置一致）。
 */
export function fanDirections(
  facing: { x: number; z: number } | undefined,
  count: number,
  spreadDeg: number,
): { x: number; z: number }[] {
  const n = Math.max(1, Math.floor(count));
  if (facing === undefined) return [];
  const l = Math.sqrt(facing.x * facing.x + facing.z * facing.z);
  if (l <= 1e-6) return [];
  const unit = { x: facing.x / l, z: facing.z / l };
  if (n === 1) return [unit];

  // ⭐ 全部在**半度刻度**上算（整數），⛔ 不是在度上算再四捨五入 ——
  //    後者會讓 ±22.5° 變成不對稱的一對。
  const wantStep = Math.round((spreadDeg < 0 ? 0 : spreadDeg) / FAN_STEP_DEG);
  const maxTotal = Math.round(FAN_MAX_TOTAL_DEG / FAN_STEP_DEG);
  const step = wantStep * (n - 1) > maxTotal ? Math.floor(maxTotal / (n - 1)) : wantStep;

  const out: { x: number; z: number }[] = [];
  for (let i = 0; i < n; i++) {
    // ⭐ 對稱：第 i 臂在 `(i − (n−1)/2) × step`。⛔ 用 `2i − (n−1)` 保持整數，
    //    再除 2 —— 半度刻度天然吸收那個 ÷2（n 為偶數時就是半格）。
    const halfDegrees = ((2 * i - (n - 1)) * step) / 2;
    // ⚠️ n 偶數且 step 為奇數格時 halfDegrees 會是 .5 —— 取最近的整數格。
    out.push(rotate(unit, rotAt(Math.round(halfDegrees))));
  }
  return out;
}
