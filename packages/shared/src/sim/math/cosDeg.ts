/**
 * ⭐ 決定性的 `cos(度數)` —— **只用 `+ − × ÷`**，⛔ 一個 `Math.cos` 都沒有。
 *
 * ── ⛔ 為什麼不能直接呼叫 `Math.cos` ──────────────────────────────────────
 * `sim/**` 的 purity 閘禁三角函式，而理由**不是潔癖**：ECMA-262 明文允許
 * `Math.sin/cos/pow/exp` 的結果是實作定義的（見 `movement/leap.ts` 檔頭第 45 行）
 * ⇒ 同一份輸入在不同 CPU／不同 V8 版本上可以差一個 ulp，而那一個 ulp 在
 * 「敵人在不在我正面 120° 內」這種**布林**判定上會變成兩台機器打出不同的一場。
 * 反過來 IEEE-754 **要求** `+ − × ÷` 與 `sqrt` 正確捨入 ⇒ 逐位元可重現。
 *
 * ── ⭐ 為什麼是 cos，⛔ 不是角度 ─────────────────────────────────────────
 * 原本的寫法是 `atan2(|cross|, dot) * 180 / π ≤ arc/2`。⭐ 兩邊取 cos 之後
 * 不等式變成 `dot ≥ cos(arc/2) · |f| · |d|` —— **左邊完全沒有三角函式**
 * （點積是乘加，長度是 `sqrt`），而右邊的 cos 只吃**作者填的那個常數**。
 * ⇒ 每一格的三角函式從「每次判定一次」降成「每次判定換算一個授權常數」，
 *   而那個換算就是這支檔案。
 *
 * ── 精度 ────────────────────────────────────────────────────────────────
 * 先把 x 規約到 [0, π/2]（`cos(π−x) = −cos(x)`，π 與 π/2 都是精確的 double，
 * 相減是正確捨入），再用泰勒展開到 x¹⁶。|x| ≤ π/2 時截斷誤差 < 1e-17，
 * ⇒ 遠小於呼叫端 1e-9 的邊界容差。⛔ 沒有用 `**`（那也是禁令）。
 */
const HALF_PI = Math.PI / 2;
const TWO_PI = Math.PI * 2;

export function cosDeg(deg: number): number {
  if (!Number.isFinite(deg)) return Number.NaN;
  // 度 → 弧度，再**完整規約**到 [0, π/2]。
  // ⚠️ ⭐ 這一段第一版只規約到 π —— 而 `cosDeg(360)` 於是落在泰勒的有效區外，
  //   誤差 **1.35e-7**（實測）。呼叫端今天只傳 ≤180°，⛔ 但一把「在定義域外會
  //   靜靜給出看似合理的錯數字」的尺，就是本專案記過三次的那個病（量尺自己說謊）。
  //   ⇒ 規約做滿：週期 → 對稱 → 半角，三步都只用 `+ − × ÷` 與 `Math.floor`。
  let x = (deg * Math.PI) / 180;
  if (x < 0) x = -x;                       // cos 是偶函數
  x = x - TWO_PI * Math.floor(x / TWO_PI); // 週期 2π
  if (x > Math.PI) x = TWO_PI - x;         // cos(2π−x) = cos(x)
  let sign = 1;
  if (x > HALF_PI) { x = Math.PI - x; sign = -1; }   // cos(π−x) = −cos(x)
  const x2 = x * x;
  // 泰勒：1 − x²/2! + x⁴/4! − ⋯ + x¹⁶/16!，用霍納法（⛔ 沒有 `**`,⛔ 沒有階乘呼叫）
  let s = 1 / 20922789888000;              // 1/16!
  s = 1 / 87178291200 - s * x2;            // 1/14!
  s = 1 / 479001600 - s * x2;              // 1/12!
  s = 1 / 3628800 - s * x2;                // 1/10!
  s = 1 / 40320 - s * x2;                  // 1/8!
  s = 1 / 720 - s * x2;                    // 1/6!
  s = 1 / 24 - s * x2;                     // 1/4!
  s = 1 / 2 - s * x2;                      // 1/2!
  return sign * (1 - s * x2);
}
