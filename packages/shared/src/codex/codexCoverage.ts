// #72's published classification — READ, NOT RE-DERIVED
// ---------------------------------------------------------------------------
//
// There is no parser here on purpose. `codexPlan.ts` is task #72's own reader
// for task #72's own artifact; duplicating it would be exactly the second,
// divergent definition of "which entries need art" that this task must not
// create. All that lives here is the ARITHMETIC over its verdict.

/** Was this entry dropped by the plan (a decision, not a gap)? */
export function isDropped(plan: CodexPlan | null, id: string): boolean {
  return plan !== null && plan.dropReason.has(id);
}

/** Is this entry blocked by the plan (needed, but gated — e.g. third-party IP)? */
export function isBlocked(plan: CodexPlan | null, id: string): boolean {
  return plan !== null && plan.blockReason.has(id);
}

// ---------------------------------------------------------------------------
// the sums
// ---------------------------------------------------------------------------

export interface CoverageBucket {
  /** entries in this collection, live */
  readonly total: number;
  /** DROPPED by the plan — a decision; leaves the denominator entirely */
  readonly excluded: number;
  /** total − excluded: the real denominator */
  readonly needed: number;
  /** needed entries whose declared icon actually resolves */
  readonly covered: number;
  /** needed − covered */
  readonly missing: number;
  /** subset of `missing` that DECLARES an icon the mount cannot serve */
  readonly broken: number;
  /** subset of `missing` the plan BLOCKS (held gate, e.g. third-party IP) */
  readonly blocked: number;
  /** missing − blocked: what generation can actually work on right now */
  readonly backlog: number;
  /** covered / needed × 100; 100 when nothing is needed */
  readonly percent: number;
}

export type ExclusionSource = "plan" | "candidate" | "none";

export interface IconCoverage {
  readonly byKind: Readonly<Record<CodexKind, CoverageBucket>>;
  readonly all: CoverageBucket;
  readonly exclusionSource: ExclusionSource;
  /** how many entries the local what-if rule WOULD exclude (hint only) */
  readonly candidateTotal: number;
  /** what the plan itself claims, for a side-by-side against the measurement */
  readonly planCounts: CodexPlan["counts"] | null;
  readonly planTemplateVersion: string | null;
  /**
   * The plan was generated against a different number of documents than we just
   * loaded — it is stale, so its exclusions may be too. Surfaced, never hidden.
   */
  readonly planStale: boolean;
}

export interface ComputeCoverageInput {
  readonly entries: readonly CoverageEntry[];
  /** #72's published verdict (codexPlan.ts); null until it lands */
  readonly plan?: CodexPlan | null;
  /** opt-in what-if using the codex's existing broken-data predicates */
  readonly applyCandidates?: boolean;
  /** icon paths the byte scan could not fetch (codexIcons.failed) */
  readonly failedIcons?: ReadonlySet<string>;
}

interface Tally {
  total: number;
  excluded: number;
  covered: number;
  broken: number;
  blocked: number;
}

function newTally(): Tally {
  return { total: 0, excluded: 0, covered: 0, broken: 0, blocked: 0 };
}

function seal(t: Tally): CoverageBucket {
  const needed = t.total - t.excluded;
  const covered = Math.min(t.covered, needed);
  const missing = Math.max(0, needed - covered);
  const blocked = Math.min(t.blocked, missing);
  return {
    total: t.total,
    excluded: t.excluded,
    needed,
    covered,
    missing,
    broken: t.broken,
    blocked,
    backlog: missing - blocked,
    percent: needed === 0 ? 100 : (covered / needed) * 100,
  };
}

/** The local what-if rule — mirrors codexIssues' `no-description` / `name-equals-id`. */
export function isCandidateExclusion(e: CoverageEntry): boolean {
  return e.emptyDescription || e.nameEqualsId;
}

export function computeIconCoverage(input: ComputeCoverageInput): IconCoverage {
  const { entries, plan = null, applyCandidates = false, failedIcons } = input;
  const tallies: Record<CodexKind, Tally> = {
    champion: newTally(),
    ability: newTally(),
    item: newTally(),
  };
  const sum = newTally();
  let candidateTotal = 0;

  for (const e of entries) {
    const t = tallies[e.kind];
    t.total++;
    sum.total++;
    if (isCandidateExclusion(e)) candidateTotal++;

    const excluded = plan ? isDropped(plan, e.id) : applyCandidates && isCandidateExclusion(e);
    if (excluded) {
      t.excluded++;
      sum.excluded++;
      continue;
    }

    if (e.icon !== null && !(failedIcons?.has(e.icon) ?? false)) {
      t.covered++;
      sum.covered++;
      continue;
    }
    if (e.icon !== null) {
      t.broken++;
      sum.broken++;
    }
    if (isBlocked(plan, e.id)) {
      t.blocked++;
      sum.blocked++;
    }
  }

  return {
    byKind: {
      champion: seal(tallies.champion),
      ability: seal(tallies.ability),
      item: seal(tallies.item),
    },
    all: seal(sum),
    exclusionSource: plan ? "plan" : applyCandidates ? "candidate" : "none",
    candidateTotal,
    planCounts: plan?.counts ?? null,
    planTemplateVersion: plan?.templateVersion ?? null,
    planStale: plan !== null && sum.total > 0 && plan.counts.docs !== sum.total,
  };
}

