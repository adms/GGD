/**
 * codexCoverage — 圖示覆蓋率 (task #97): how many champion / ability / item
 * icons EXIST against how many are actually NEEDED.
 *
 * WHY IT EXISTS. The user asked for it in exactly these terms:
 * 「生成必要 英雄、技能、武器道具 icon 是否能給我一個即時的數量進度條，讓我知道你
 * 真的有在作事而不是忘了」 — the point is VERIFICATION, not decoration. So every
 * number below is DERIVED, never asserted:
 *
 *   • the DENOMINATOR is the live length of each collection as fetched from
 *     /content by whichever page is counting (the codex's ui/codex/codexData.ts,
 *     後台管理's assets/useIconTracking.ts). Nothing here may carry a size — the
 *     `codex-no-baked-content` gate fails the build if a literal one appears,
 *     and that gate is load-bearing for this module in particular: a progress
 *     bar with a typed-in total is worse than no progress bar at all.
 *   • the NUMERATOR is the `icon` field each fetched doc declares, minus the
 *     paths the background icon-byte scan (codexIcons.ts) could not actually
 *     fetch. A doc that declares art the server cannot serve is NOT covered.
 *
 * NEEDS AN ICON vs DELIBERATELY EXCLUDED. The user also ruled that entries
 * obviously not meant for play get no art (「明顯不是提供使用的(ex.空描述)就不需要
 * 了」). TASK #72 OWNS THAT CLASSIFICATION, and this module does not re-derive a
 * word of it: the verdict is read through `codexPlan.ts` — #72's own reader for
 * its own artifact, `content/config/icon-plan.json`, regenerated by
 * `tools/icon-gen/src/plan.py`. Three states come back and they are NOT the
 * same thing, which is exactly why the bar has to show them apart:
 *
 *   DROPPED  a decision — never generate. Leaves the DENOMINATOR entirely.
 *   BLOCKED  a held gate (third-party IP) — still needed, still counted, but
 *            not work anyone can do yet. Its own band, its own colour.
 *   BACKLOG  the honest remainder. This is what the bar is a bar OF.
 *
 * Until the plan exists the bar counts every icon-less entry as needed and says
 * so. `candidate*` is an opt-in what-if using the codex's own pre-existing
 * broken-data predicates (ui/codex/codexIssues.ts: `no-description`,
 * `name-equals-id`) —
 * labelled as a guess, never the default, and always beaten by a real plan, so
 * it cannot quietly diverge from #72's answer.
 *
 * Pure and total: no fetch, no React, no clock. The React hooks do the I/O —
 * the codex's own `apps/client/src/ui/codex/useIconCoverage.ts` and 後台管理's
 * `apps/admin/src/assets/useIconTracking.ts` — and the tests drive these
 * functions directly, so the numbers in the tests are the numbers on the page.
 *
 * WHY THIS FILE IS IN packages/shared AND NOT ui/codex, where it was written:
 * two pages now count icons — the in-game codex bar and 後台管理's ICON 生成追蹤
 * (task #102) — and a second implementation of "how many icons are missing"
 * would diverge from this one within a day, leaving both numbers worthless.
 * Both apps already depend on @ggd/shared, so one definition can serve both.
 * The `codex-no-baked-content` gate (apps/client/src/ui/codex/codexLive.test.ts)
 * scans this directory too: moving out of ui/codex did not move out of reach.
 */
import type { CodexPlan } from "./codexPlan";
import type { CodexData, CodexKind } from "./codexTypes";

/** Display order the user named them in: 英雄 / 技能 / 武器道具. */
export const COVERAGE_KINDS: readonly CodexKind[] = ["champion", "ability", "item"];

/** kind → the content collection it lives in (same mapping the loader uses). */
export const COVERAGE_COLLECTION: Readonly<Record<CodexKind, string>> = {
  champion: "champions",
  ability: "abilities",
  item: "items",
};


// ---------------------------------------------------------------------------
// the unit of measurement
// ---------------------------------------------------------------------------

/**
 * One entry reduced to just what coverage needs. Deliberately tiny: the live
 * rescan re-reads changed docs and swaps these in without disturbing the
 * browsing data the page is rendering from.
 */
export interface CoverageEntry {
  readonly kind: CodexKind;
  readonly id: string;
  /** the `icon` path the doc declares; null when it declares none */
  readonly icon: string | null;
  /** no usable `description` — the first half of #72's exclusion rule */
  readonly emptyDescription: boolean;
  /** display name fell back to the id — the second half */
  readonly nameEqualsId: boolean;
}

export function coverageKey(kind: CodexKind, id: string): string {
  return `${kind}/${id}`;
}

function asRecord(v: unknown): Record<string, unknown> | null {
  return typeof v === "object" && v !== null && !Array.isArray(v) ? (v as Record<string, unknown>) : null;
}
function nonEmpty(v: unknown): string | null {
  return typeof v === "string" && v !== "" ? v : null;
}

/** Reduce a loaded codex to coverage entries — zero extra requests. */
export function coverageEntries(data: CodexData): CoverageEntry[] {
  const out: CoverageEntry[] = [];
  for (const c of data.champions) {
    out.push({
      kind: "champion",
      id: c.id,
      icon: c.icon,
      emptyDescription: c.description === null,
      nameEqualsId: c.name === c.id,
    });
  }
  for (const a of data.abilities) {
    out.push({
      kind: "ability",
      id: a.id,
      icon: a.icon,
      emptyDescription: a.description === null,
      nameEqualsId: a.name === a.id,
    });
  }
  for (const i of data.items) {
    out.push({
      kind: "item",
      id: i.id,
      icon: i.icon,
      emptyDescription: i.description === null,
      nameEqualsId: i.name === i.id,
    });
  }
  return out;
}

/**
 * Read one raw doc (as re-fetched by the live rescan) into a coverage entry.
 * Same tolerance as codexData's normalisers: a broken doc still counts, it just
 * counts as having no icon.
 */
export function coverageEntryFromDoc(kind: CodexKind, id: string, raw: unknown): CoverageEntry {
  const doc = asRecord(raw) ?? {};
  return {
    kind,
    id,
    icon: nonEmpty(doc["icon"]),
    emptyDescription: nonEmpty(doc["description"]) === null,
    nameEqualsId: (nonEmpty(doc["name"]) ?? id) === id,
  };
}

