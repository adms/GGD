/**
 * One row of a collection's `_index.json`. The `hash` is what makes the live
 * bar cheap: it is a stable hash of the PARSED doc (fsStore.hashDoc), so
 * writing an `icon` field changes it while a reformat does not. Polling the
 * three index files is 3 requests; only the docs whose hash moved get re-read.
 */
export interface IndexRow {
  readonly kind: CodexKind;
  readonly id: string;
  readonly path: string;
  readonly hash: string;
}

/** What the rescan carries between polls. */
export interface CoverageScan {
  readonly entries: readonly CoverageEntry[];
  /** coverageKey → the index hash already reconciled into `entries` */
  readonly hashes: ReadonlyMap<string, string>;
}

export function scanFromEntries(entries: readonly CoverageEntry[]): CoverageScan {
  return { entries, hashes: new Map() };
}

/** Read `{entries:[{id,path,hash}]}` off a fetched `_index.json`. */
export function parseIndexRows(kind: CodexKind, raw: unknown): IndexRow[] {
  const list = asRecord(raw)?.["entries"];
  if (!Array.isArray(list)) return [];
  const out: IndexRow[] = [];
  for (const row of list) {
    const rec = asRecord(row);
    const id = rec ? nonEmpty(rec["id"]) : null;
    const path = rec ? nonEmpty(rec["path"]) : null;
    const hash = rec ? nonEmpty(rec["hash"]) : null;
    if (id && path && hash) out.push({ kind, id, path, hash });
  }
  return out;
}

export interface DiffResult {
  /** pruned scan — entries whose id vanished from the index are dropped */
  readonly scan: CoverageScan;
  /** docs that must be re-read before their coverage can be trusted */
  readonly stale: readonly IndexRow[];
}

/**
 * Reconcile a freshly polled index against the last scan.
 *
 * FIRST POLL IS FREE: an entry the codex load already produced adopts its index
 * hash without a re-read (we have the doc's icon field already), so opening the
 * page costs 3 extra requests, not one per document.
 *
 * `kinds` lists the collections whose index actually came back. A collection
 * that failed to fetch is left completely alone — a network blip must never
 * read as "every icon disappeared".
 */
export function diffScan(
  prev: CoverageScan,
  rows: readonly IndexRow[],
  kinds: readonly CodexKind[],
): DiffResult {
  const seen = new Set(kinds);
  const byKey = new Map<string, IndexRow>();
  for (const r of rows) byKey.set(coverageKey(r.kind, r.id), r);

  const known = new Map<string, CoverageEntry>();
  for (const e of prev.entries) known.set(coverageKey(e.kind, e.id), e);

  const entries: CoverageEntry[] = [];
  for (const e of prev.entries) {
    const key = coverageKey(e.kind, e.id);
    if (!seen.has(e.kind) || byKey.has(key)) entries.push(e);
  }

  const hashes = new Map<string, string>();
  const stale: IndexRow[] = [];
  for (const [key, row] of byKey) {
    const priorHash = prev.hashes.get(key);
    if (priorHash === row.hash) {
      hashes.set(key, row.hash);
      continue;
    }
    if (priorHash === undefined && known.has(key)) {
      // first sighting of a doc the codex load already read — adopt, don't refetch
      hashes.set(key, row.hash);
      continue;
    }
    stale.push(row);
    if (priorHash !== undefined) hashes.set(key, priorHash);
  }
  // keep hashes for kinds whose index did not come back this round
  for (const [key, hash] of prev.hashes) {
    const kind = key.slice(0, key.indexOf("/")) as CodexKind;
    if (!seen.has(kind) && !hashes.has(key)) hashes.set(key, hash);
  }
  return { scan: { entries, hashes }, stale };
}

/** Fold re-read docs back in, marking their index hash as reconciled. */
export function mergeDocs(
  prev: CoverageScan,
  updates: readonly { readonly row: IndexRow; readonly doc: unknown }[],
): CoverageScan {
  if (updates.length === 0) return prev;
  const byKey = new Map<string, CoverageEntry>();
  for (const e of prev.entries) byKey.set(coverageKey(e.kind, e.id), e);
  const hashes = new Map(prev.hashes);
  for (const { row, doc } of updates) {
    const key = coverageKey(row.kind, row.id);
    byKey.set(key, coverageEntryFromDoc(row.kind, row.id, doc));
    hashes.set(key, row.hash);
  }
  return { entries: [...byKey.values()], hashes };
}
